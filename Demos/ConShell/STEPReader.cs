using static STEPReader.EType;

public class STEPReader {
   public STEPReader (string file) {
      R = new (D = File.ReadAllBytes (mFile = file));
   }

   public void Load () {
      ReadOnlySpan<byte> seq = "DATA;"u8;
      if (!R.Find (seq)) throw new Exception ("DATA section not found");
      int idMax = 0;
      for (; ; ) {
         R.SkipToNextLine ();
         if (R.TryMatch ('#')) {
            R.Read (out int id);
            if (R.SkipSpace ().TryMatch ('=')) {
               idMax = Math.Max (idMax, id);
               R.SkipSpace ();
               if (R.Peek () == '(') { } else {
                  EType type = RType ();
               }
            }
         } else {
            if (R.TryMatch ("ENDSEC;"u8)) break;
         }
      }
      Console.Write ($" {idMax} ");
   }

   EType RType () {
      var span = R.TakeUntil ('(');
      EType type = Dict.GetValueOrDefault (span);
      if (type == _NIL && span[^1] == ' ') 
            type = Dict.GetValueOrDefault (span[..^1]);
      if (type == _NIL) { 
         string s = $"Unknown: {Encoding.ASCII.GetString (span)}, line {R.LineNo} of {mFile}";
         throw new Exception (s);
      }
      return type;
   }

   // The SymTable that maps spans of bytes (characters) to E values
   static SymTable<EType> Dict {
      get {
         if (sDict == null) {
            sDict = new ();
            for (var ed = _FIRST; ed <= _LAST; ed++) {
               var s = ed.ToString ();
               sDict.Add (s, ed);
            }
         }
         return sDict;
      }
   }
